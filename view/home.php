<h2>Selamat Datang</h2>
<p>Aplikasi ini mencatat aktivitas ekspor dan impor di pelabuhan internasional.</p>
<ul>
    <li><strong>Kapal</strong>: data kapal pengangkut (nomor IMO, bendera, kapasitas TEU).</li>
    <li><strong>Barang</strong>: komoditas yang diperdagangkan (kode HS, kategori).</li>
    <li><strong>Transaksi Ekspor/Impor</strong>: pengiriman yang menghubungkan kapal dan barang.</li>
</ul>
